<?php
run_group('content', function() use ($db,$config) {
    check(class_exists('Articles'), 'article service exists');
    $auth=new Auth($db);
    $uid=$auth->saveAdmin(['username'=>'writer','display_name'=>'Writer','password'=>'Only-For-Testing-9283','active'=>1],null);
    $articles=new Articles($db);
    $media=new Media($db);
    $html=new Html($db);
    $categories=new Categories($db);
    $id=$articles->create($uid);
    check($articles->get($id)===null,'new draft hidden');
    $original=['title'=>'Reset your password','category_id'=>1,'keywords'=>'login account','html'=>'<h2>Start here</h2><p>Original instructions.</p>'];
    $articles->save($id,$original,1,$uid,true);
    $rev=(int)$articles->get($id)['revision_id'];
    $changed=$original; $changed['title']='Unpublished secret'; $changed['html']='<p>Draft secret</p>';
    $articles->save($id,$changed,2,$uid,false);
    check($articles->get($id)['title']===$original['title'],'draft title private');
    check(!str_contains($articles->get($id)['html'],'secret'),'draft body private');
    expect_error(fn()=> $articles->save($id,$changed,1,$uid,true),'another');
    $safe=$html->clean('<p onclick="alert(1)">Text<script>alert(1)</script><a href="javascript:alert(1)">link</a><iframe src="http://evil.test"></iframe><img src="https://evil.test/track.png"></p>',$id);
    check(!preg_match('/script|onclick|iframe|evil\.test/i',$safe),'unsafe HTML filtered');
    check(str_contains($safe,'Text'),'safe text preserved');
    $path=tempnam(sys_get_temp_dir(),'kbpng');
    $im=imagecreatetruecolor(16,16); imagepng($im,$path); imagedestroy($im);
    $m1=$media->store($id,$path,$uid); $m2=$media->store($id,$path,$uid); unlink($path);
    check($media->find($m1['id'],false)===null,'unpublished image private');
    $withImage=$original; $withImage['html'].='<img src="'.e($m1['location']).'" alt="Screen">';
    $articles->save($id,$withImage,3,$uid,true);
    check($media->find($m1['id'],false)!==null,'published image readable');
    check($media->find($m2['id'],false)===null,'new draft image on published article stays private');
    check($media->find($m2['id'],true)!==null,'admin can preview draft image');
    $other=$articles->create($uid);
    expect_error(fn()=> $html->clean('<img src="'.e($m1['location']).'">',$other),'image');
    $bad=tempnam(sys_get_temp_dir(),'badimage'); file_put_contents($bad,'<?php echo "not an image";');
    expect_error(fn()=> $media->store($id,$bad,$uid),'image'); unlink($bad);
    $articles->restoreRevision($id,$rev,4,$uid);
    check($articles->get($id,true)['title']===$original['title'],'revision loaded into draft');
    check(str_contains($articles->get($id)['html'],'img'),'revision restore does not republish');
    $articles->save($id,$articles->get($id,true),5,$uid,true);
    check($media->find($m1['id'],false)===null,'removed image hidden');
    $articles->trash($id,6);
    check($articles->get($id)===null,'trash hidden from employees');
    $articles->restore($id,7);
    check($articles->get($id)===null,'trash restore returns draft');
    $articles->save($id,$original,8,$uid,true);
    check($articles->get($id)['id']===$id,'article permanent id unchanged');
    expect_error(fn()=> $categories->delete(1),'move');
    $cat=$categories->save('Temporary category',null);
    $categories->save('Renamed category',$cat);
    check(in_array('Renamed category',array_column($categories->all(false),'name'),true),'category rename');
    $categories->delete($cat);
    expect_error(fn()=> $articles->save($id,['title'=>'','category_id'=>1,'keywords'=>'','html'=>'x'],9,$uid,true),'title');
    check($articles->get($id)['title']===$original['title'],'failed save preserves published content');
});
